function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function make(p) {
  const stone = STONES[p.stone];
  const sizes = SIZES[p.type];
  return {
    slug: slugify(p.name),
    color: stone.color,
    gemstone: stone.gemstone,
    sizes: sizes.options,
    defaultSize: sizes.default,
    customizationFee: p.customizable.size || p.customizable.color ? p.customizationFee : 0,
    details: `${p.shortDescription} ${TYPE_DETAILS[p.type]}`,
    images: [],
    ...p,
  };
}

